const test=require('node:test'),assert=require('node:assert/strict');
const {createWalkthrough}=require('./walkthrough-fixture.cjs');
const fs=require('node:fs'),path=require('node:path'),{JSDOM}=require('jsdom');
test('isolated Forecast executes the actual admin route and model, with external AI/research explicitly disconnected',async t=>{
    const engine=await createWalkthrough({origin:'https://127.0.0.1:9443'});t.after(()=>engine.close());
    const response=await engine.request('forecast','GET',null,'admin');
    assert.equal(response.status,200);const initial=await response.json();
    assert.equal(initial.capabilities.ai.available,false);assert.equal(initial.capabilities.research.available,false);
    assert.equal(initial.capabilities.catalog.available,false);assert.equal(initial.scenario.markets.length,1);
    const denied=await engine.request('forecast','GET',null,'sales');assert.equal(denied.status,403);
    const calculated=await engine.request('forecast','POST',{action:'calculate',scenario:initial.scenario},'admin');
    assert.equal(calculated.status,200);const data=await calculated.json();
    assert.equal(data.comparisons.length,1);
    assert.equal(data.comparisons[0].cases.find(item=>item.name==='base').metrics.operatingProfitCents,null);
    assert.equal(data.comparisons[0].evidence.length,0);
    const ai=await engine.request('forecast','POST',{action:'interpret',text:'Compare Dallas and Los Angeles',scenario:initial.scenario},'admin');
    assert.equal(ai.status,503);assert.match((await ai.json()).error,/AI.*unavailable/i);
});
